/* ---------------------------------------------------------------- Skeleton */

export const Skeleton = ({ className = '', rows = 3 }) => (
  <div className={`space-y-2 ${className}`}>
    {Array.from({ length: rows }).map((_, i) => (
      <div key={i} className="h-4 bg-surface-sunken rounded-sm animate-pulse" style={{ width: `${88 - i * 12}%` }} />
    ))}
  </div>
);

/* --------------------------------------------------------------- DataTable */

/**
 * Dense operational table. Flat geometry, border-separated, no zebra —
 * rows read as records, not as decoration.
 */
export const DataTable = ({
  columns, rows, getKey, onRowClick, rowClassName, dense = true, empty, className = '',
}) => (
  <div className={`overflow-x-auto custom-scrollbar ${className}`}>
    <table className="w-full text-left border-collapse text-xs">
      <thead className="bg-surface-sunken border-b border-line sticky top-0 z-10">
        <tr>
          {columns.map((c) => (
            <th
              key={c.key}
              className={`px-3 py-2 t-label whitespace-nowrap ${c.align === 'right' ? 'text-right' : ''} ${c.thClassName || ''}`}
              style={c.width ? { width: c.width } : undefined}
            >
              {c.header}
            </th>
          ))}
        </tr>
      </thead>
      <tbody>
        {rows.length === 0 && (
          <tr>
            <td colSpan={columns.length}>
              {empty || <EmptyState title="No records match the current filters." />}
            </td>
          </tr>
        )}
        {rows.map((row) => (
          <tr
            key={getKey(row)}
            onClick={onRowClick ? () => onRowClick(row) : undefined}
            className={`border-b border-line-subtle last:border-b-0 ${
              onRowClick ? 'cursor-pointer hover:bg-status-info-tint/60' : ''
            } ${rowClassName ? rowClassName(row) : ''}`}
          >
            {columns.map((c) => (
              <td
                key={c.key}
                className={`px-3 ${dense ? 'py-1.5' : 'py-2'} align-middle ${c.align === 'right' ? 'text-right' : ''} ${c.tdClassName || ''}`}
              >
                {c.render ? c.render(row) : row[c.key]}
              </td>
            ))}
          </tr>
        ))}
      </tbody>
    </table>
  </div>
);
